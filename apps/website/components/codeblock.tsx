"use client";
import {
  type ComponentProps,
  createContext,
  type HTMLAttributes,
  type ReactNode,
  type RefObject,
  useContext,
  useLayoutEffect,
  useRef,
} from "react";
import { cn } from "@/lib/cn";
import { CopyButton as CustomCopyButton } from "./ui/copy-button";

export interface CodeBlockProps extends ComponentProps<"figure"> {
  /**
   * Icon of code block
   *
   * When passed as a string, it assumes the value is the HTML of icon
   */
  icon?: ReactNode;

  /**
   * Allow to copy code with copy button
   *
   * @defaultValue true
   */
  allowCopy?: boolean;

  /**
   * Keep original background color generated by Shiki or Rehype Code
   *
   * @defaultValue false
   */
  keepBackground?: boolean;

  viewportProps?: HTMLAttributes<HTMLElement>;

  /**
   * show line numbers
   */
  "data-line-numbers"?: boolean;

  /**
   * @defaultValue 1
   */
  "data-line-numbers-start"?: number;

  Actions?: (props: { className?: string; children?: ReactNode }) => ReactNode;
}

const TabsContext = createContext<{
  containerRef: RefObject<HTMLDivElement | null>;
  nested: boolean;
} | null>(null);

export function Pre(props: ComponentProps<"pre">) {
  return (
    <pre
      {...props}
      className={cn("min-w-full w-max *:flex *:flex-col", props.className)}
    >
      {props.children}
    </pre>
  );
}

export function CodeBlock({
  ref,
  title,
  allowCopy = true,
  keepBackground = false,
  icon,
  viewportProps = {},
  children,
  Actions = (props) => (
    <div {...props} className={cn("empty:hidden", props.className)} />
  ),
  ...props
}: CodeBlockProps) {
  const inTab = useContext(TabsContext) !== null;
  const areaRef = useRef<HTMLDivElement>(null);

  useLayoutEffect(() => {
    const viewport = areaRef.current;
    const figure = viewport?.closest("figure");
    if (!viewport || !figure) return;

    // Inspect rendered source so MDX, plain text, and highlighted/tabbed code
    // all get the same layout without requiring flags on individual pages.
    const updateLayout = () => {
      const blocks = viewport.querySelectorAll("pre");
      const source = blocks[0]?.textContent?.trimEnd() ?? "";
      figure.toggleAttribute(
        "data-single-line",
        blocks.length === 1 && source.length > 0 && !source.includes("\n")
      );
      if (figure.hasAttribute("data-single-line")) {
        // Include optional filename headers when positioning Copy beside the code.
        const content = viewport.getBoundingClientRect();
        figure.style.setProperty(
          "--site-code-copy-y",
          `${content.top - figure.getBoundingClientRect().top + content.height / 2}px`
        );
      }
    };
    const observer = new MutationObserver(updateLayout);
    observer.observe(viewport, {
      childList: true,
      characterData: true,
      subtree: true,
    });
    const resizeObserver = new ResizeObserver(updateLayout);
    resizeObserver.observe(viewport);
    updateLayout();
    return () => {
      observer.disconnect();
      resizeObserver.disconnect();
    };
  }, []);

  return (
    <figure
      ref={ref}
      dir="ltr"
      {...props}
      className={cn(
        inTab ? "bg-fd-secondary -mx-px -mb-px" : "my-2 bg-fd-card",
        keepBackground && "bg-(--shiki-light-bg) dark:bg-(--shiki-dark-bg)",
        "group shiki relative border border-brand-neutral-500 bg-brand-black/60 outline-none not-prose overflow-hidden text-sm rounded-lg",
        props.className
      )}
    >
      {title ? (
        <div className="flex items-center gap-2 h-10 border-b px-4 border-brand-neutral-500 text-brand-neutral-100">
          {typeof icon === "string" ? (
            <div
              className="[&_svg]:size-3.5"
              dangerouslySetInnerHTML={{
                __html: icon,
              }}
            />
          ) : (
            icon
          )}
          <figcaption className="flex-1 truncate">{title}</figcaption>
          {Actions({
            className: "site-code-actions",
            children: allowCopy && <CopyButton containerRef={areaRef} />,
          })}
        </div>
      ) : (
        Actions({
          className: "site-code-actions absolute top-2.5 right-2.5 z-2",
          children: allowCopy && <CopyButton containerRef={areaRef} />,
        })
      )}
      <div
        ref={areaRef}
        {...viewportProps}
        className={cn(
          "site-code-viewport text-[13px] overflow-auto max-h-[600px] sidebar-scrollbar",
          viewportProps.className
        )}
        style={
          {
            // space for toolbar
            "--padding-right": !title ? "80px" : undefined,
            counterSet: props["data-line-numbers"]
              ? `line ${Number(props["data-line-numbers-start"] ?? 1) - 1}`
              : undefined,
            ...viewportProps.style,
          } as object
        }
      >
        {children}
      </div>
    </figure>
  );
}

function CopyButton({
  className,
  containerRef,
}: {
  containerRef: RefObject<HTMLElement | null>;
  className?: string;
}) {
  function getText() {
    const pre = containerRef.current?.querySelector("pre");
    if (!pre) return "";
    const clone = pre.cloneNode(true) as HTMLElement;
    clone
      .querySelectorAll(".nd-copy-ignore")
      .forEach((node) => node.replaceWith("\n"));
    return clone.textContent ?? "";
  }
  return <CustomCopyButton text={getText} label className={className} />;
}
